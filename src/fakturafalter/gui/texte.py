def hinweis_text(text: str) -> str:
    """Hinweise der Pipeline übersetzen; interpolierte Texte über die Vorlage."""
    m = _KONTROLLE_OFFEN_RE.match(text)
    if m:
        return _(KONTROLLE_OFFEN).format(profil=m.group(1), kennung=m.group(2), name=_(m.group(3)))
    m = _EINHEIT_KLAMMER_RE.match(text)
    if m:
        return _(EINHEIT_KLAMMER).format(i=m.group(1), einheit=m.group(2))
    m = _ZAHLUNG_OHNE_VORLAGE_RE.match(text)
    if m:
        return _(ZAHLUNG_OHNE_VORLAGE).format(text=m.group(1))
    m = _ZAHLUNG_NICHT_AN_STELLE_RE.match(text)
    if m:
        return _(ZAHLUNG_NICHT_AN_STELLE).format(text=m.group(1))
    return _(text)

